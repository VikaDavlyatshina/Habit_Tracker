from django.conf import settings
from django.db import models


class Habit(models.Model):
    """
    Модель привычки для трекера.

    Полезная привычка — действие, которое пользователь выполняет регулярно.
    За выполнение полезной привычки можно получить:
      - приятную привычку (related_habit), ИЛИ
      - вознаграждение (reward)

    Приятная привычка — награда за выполнение полезной.
    У приятной привычки не может быть своего вознаграждения или связанной привычки.

    Пример:
      Полезная: "Пробежка в парке в 07:00" → награда: "Принять ванну" (приятная)
      Полезная: "Не опаздывать на встречу" → награда: "Заказать десерт" (вознаграждение)
    """

    # ============================================
    # СВЯЗЬ С ПОЛЬЗОВАТЕЛЕМ
    # ============================================
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,  # Берём модель пользователя из настроек
        on_delete=models.CASCADE,  # При удалении пользователя — удалить все его привычки
        related_name='habits',  # Позволяет получить все привычки: user.habits.all()
        verbose_name='Пользователь'
    )

    # ============================================
    # ГДЕ И КОГДА ВЫПОЛНЯТЬ
    # ============================================
    place = models.CharField(
        max_length=255,  # Название места — короткий текст
        verbose_name='Место',
        help_text='Где выполнять привычку (например, "Парк", "Дом", "Офис")'
    )
    time = models.TimeField(
        verbose_name='Время',
        help_text='Во сколько выполнять привычку (например, 08:00)'
    )

    # ============================================
    # ЧТО ДЕЛАТЬ
    # ============================================
    action = models.CharField(
        max_length=255,  # Описание действия — короткий текст
        verbose_name='Действие',
        help_text='Что именно делать (например, "Пробежка 3 км")'
    )

    # ============================================
    # ТИП ПРИВЫЧКИ (полезная / приятная)
    # ============================================
    is_pleasant = models.BooleanField(
        default=False,  # По умолчанию привычка — полезная
        verbose_name='Приятная привычка',
        help_text=(
            'Отметьте, если это ПРИЯТНАЯ привычка (награда за полезную). '
            'У приятной привычки НЕ может быть вознаграждения или связанной привычки.'
        )
    )

    # ============================================
    # СВЯЗАННАЯ ПРИЯТНАЯ ПРИВЫЧКА (награда)
    # ============================================
    related_habit = models.ForeignKey(
        'self',  # Ссылается на другую запись этой же модели
        on_delete=models.SET_NULL,  # Если связанную привычку удалят — связь обнулится
        null=True,  # В базе данных может быть NULL (поле необязательное)
        blank=True,  # В формах можно оставить пустым
        related_name='useful_habits',  # Доступ в обратную сторону: приятная_привычка.useful_habits.all()
        verbose_name='Связанная привычка',
        help_text=(
            'Приятная привычка-награда за выполнение этой полезной. '
            'Нельзя заполнить одновременно с Вознаграждением.'
        )
    )

    # ============================================
    # ПЕРИОДИЧНОСТЬ (как часто повторять)
    # ============================================
    period = models.IntegerField(
        default=1,  # По умолчанию — каждый день
        verbose_name='Периодичность (дни)',
        help_text='Через сколько дней повторять привычку. От 1 (каждый день) до 7 (раз в неделю)'
    )

    # ============================================
    # ВОЗНАГРАЖДЕНИЕ (альтернатива связанной привычке)
    # ============================================
    reward = models.CharField(
        max_length=255,
        blank=True,  # Можно не заполнять (если выбрана related_habit)
        null=True,  # В базе может быть NULL
        verbose_name='Вознаграждение',
        help_text=(
            'Чем наградить себя за выполнение (например, "Съесть десерт"). '
            'Нельзя заполнить одновременно со Связанной привычкой.'
        )
    )

    # ============================================
    # ВРЕМЯ НА ВЫПОЛНЕНИЕ (не более 120 секунд)
    # ============================================
    duration = models.IntegerField(
        verbose_name='Время выполнения (секунды)',
        help_text='Сколько секунд выполнять привычку. Максимум 120 секунд (2 минуты)'
    )

    # ============================================
    # ПУБЛИЧНОСТЬ (доступна ли другим пользователям)
    # ============================================
    is_public = models.BooleanField(
        default=False,  # По умолчанию привычка — личная
        verbose_name='Публичная',
        help_text='Если отмечено — другие пользователи увидят эту привычку в общем списке'
    )

    # ============================================
    # СЛУЖЕБНЫЕ ПОЛЯ (заполняются автоматически)
    # ============================================
    created_at = models.DateTimeField(
        auto_now_add=True,  # Автоматически ставится при создании (один раз)
        verbose_name='Создана'
    )
    updated_at = models.DateTimeField(
        auto_now=True,  # Автоматически обновляется при каждом сохранении
        verbose_name='Обновлена'
    )

    # ============================================
    # МЕТА-НАСТРОЙКИ (как модель отображается)
    # ============================================
    class Meta:
        verbose_name = 'Привычка'  # Название в админке (ед. число)
        verbose_name_plural = 'Привычки'  # Название в админке (мн. число)
        ordering = ['-created_at']  # Сортировка: сначала новые

    # ============================================
    # СТРОКОВОЕ ПРЕДСТАВЛЕНИЕ (как выглядит в админке и shell)
    # ============================================
    def __str__(self):
        prefix = 'Приятная' if self.is_pleasant else 'Полезная'
        return f'{prefix}: {self.action} в {self.time} ({self.place})'